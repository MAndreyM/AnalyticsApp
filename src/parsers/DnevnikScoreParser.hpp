#pragma once
#include <string>

/**
 * @class DnevnikScoreParser
 * @brief Парсер для преобразования строковых баллов из формата "Дневник.ру"
 * 
 * Класс предоставляет статические методы для преобразования баллов из формата,
 * используемого в системе "Дневник.ру", где баллы представлены целыми числами
 * в диапазоне 0-5000 (где 5000 соответствует 5.0), в десятичные числа.
 * 
 * Формат преобразования:
 * - "3690" → 3.690
 * - "5000" → 5.000
 * - "0" → 0.000
 * 
 * Также обрабатывает некорректные данные, возвращая 0.0 в случае ошибок.
 */
class DnevnikScoreParser {
public:
    /**
     * @brief Преобразует строковое представление балла в десятичное число
     * 
     * @param scoreStr Строка, содержащая балл в формате "Дневник.ру" (например, "3690")
     * @return double Десятичное значение балла (например, 3.690)
     * 
     * @details
     * Алгоритм преобразования:
     * 1. Удаление всех пробелов из строки
     * 2. Преобразование строки в целое число
     * 3. Деление на 1000.0 для получения десятичного значения
     * 
     * Обработка ошибок:
     * - Пустая строка → 0.0
     * - Строка только из пробелов → 0.0
     * - Некорректное числовое значение → 0.0
     * 
     * @note
     * - Входной формат: целые числа от 0 до 5000
     * - Выходной формат: десятичные числа от 0.0 до 5.0
     * - Точность: до 3 знаков после запятой
     */
    static double parseScore(const std::string& scoreStr);
    
    /**
     * @brief Нормализует строку для парсинга
     * 
     * @param scoreStr Исходная строка с баллом
     * @return std::string Нормализованная строка (без пробелов)
     * 
     * @details
     * Выполняет следующие операции:
     * 1. Удаляет все пробелы из строки
     * 2. Проверяет, что строка не пуста
     * 3. Возвращает подготовленную строку для дальнейшего парсинга
     */
    static std::string normalizeString(const std::string& scoreStr);

};