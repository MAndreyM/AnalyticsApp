#pragma once

#include <unordered_map>
#include <string>
#include <vector>

/**
 * @class SubjectMapper
 * @brief Класс для преобразования сокращенных названий предметов в полные.
 * 
 * Предоставляет функциональность для маппинга сокращенных названий учебных предметов
 * (как они встречаются в файлах "Дневник.ру") на их полные названия.
 * Поддерживает расширяемость через добавление новых соответствий.
 */
class SubjectMapper {
public:
    /**
     * @brief Конструктор по умолчанию.
     * 
     * Инициализирует внутренний словарь соответствий сокращений полным названиям.
     */
    SubjectMapper();
    
    /**
     * @brief Получить полное название предмета по сокращению.
     * 
     * @param shortName Сокращенное название предмета.
     * @return Полное название предмета. Если сокращение не найдено,
     *         возвращает исходное сокращение.
     */
    std::string getFullName(const std::string& shortName) const;
    
    /**
     * @brief Проверить наличие сокращения в словаре.
     * 
     * @param shortName Сокращенное название предмета для проверки.
     * @return true - сокращение найдено в словаре, false - не найдено.
     */
    bool contains(const std::string& shortName) const;
    
    /**
     * @brief Получить количество соответствий в словаре.
     * 
     * @return Количество пар "сокращение-полное_название" в словаре.
     */
    size_t size() const;
    
    /**
     * @brief Добавить новое соответствие в словарь.
     * 
     * @param shortName Сокращенное название предмета.
     * @param fullName Полное название предмета.
     */
    void addMapping(const std::string& shortName, const std::string& fullName);
    
    /**
     * @brief Получить список всех сокращений из словаря.
     * 
     * @return Вектор всех сокращенных названий предметов в алфавитном порядке.
     */
    std::vector<std::string> getAllShortNames() const;
    
    /**
     * @brief Очистить словарь соответствий.
     * 
     * Удаляет все сохраненные соответствия сокращений полным названиям.
     */
    void clear();

private:
    /// Внутренний словарь для хранения соответствий сокращений полным названиям
    std::unordered_map<std::string, std::string> subjectMap;
    
    /**
     * @brief Инициализировать словарь стандартными значениями.
     * 
     * Заполняет словарь предопределенными соответствиями для школьных предметов,
     * которые встречаются в файлах системы "Дневник.ру".
     */
    void initializeMap();
    
    /**
     * @brief Удалить пробельные символы с начала и конца строки.
     * 
     * @param str Исходная строка.
     * @return Строка без пробельных символов в начале и конце.
     * 
     * Удаляет символы: пробел, табуляция, новая строка, возврат каретки,
     * перевод страницы, вертикальная табуляция.
     */
    static std::string trim(const std::string& str);
};